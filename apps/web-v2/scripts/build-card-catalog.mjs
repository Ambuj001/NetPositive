// Builds src/lib/cardCatalog.data.ts from the card list in chatbot/data/cards.json (the list the product owner supplied).
// Run: npm run catalog:build      A test (test/cardCatalog.test.ts) fails if the committed file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const SOURCE = path.resolve(here, '../../../chatbot/data/cards.json');
export const OUT = path.resolve(here, '../src/lib/cardCatalog.data.ts');

const ROUTE_FIELDS = ['id', 'channel', 'kind', 'verified', 'unit', 'base_pts', 'mult', 'discount_pct', 'reward_pct', 'bonus_cap_pts', 'note'];

/** The data this app needs: every card available in India, with the voucher routes known for it. */
export function buildCatalogData(json) {
  const routesByCard = new Map();
  for (const r of json.routes) {
    const slim = Object.fromEntries(ROUTE_FIELDS.filter((k) => r[k] !== undefined).map((k) => [k, r[k]]));
    routesByCard.set(r.card_id, [...(routesByCard.get(r.card_id) ?? []), slim]);
  }
  const cards = json.cards
    .filter((c) => !c.regions || c.regions.includes('IN')) // region-locked cards (for example EEA only) are not offered here
    .map((c) => ({ id: c.id, name: c.name, issuer: c.issuer, aliases: c.aliases ?? [], routes: routesByCard.get(c.id) ?? [] }));
  return { cards, maxVoucherDenomination: json.cards ? json._meta.max_voucher_denomination : 5000 };
}

export function render(data) {
  return `// GENERATED by scripts/build-card-catalog.mjs from chatbot/data/cards.json. Do not edit by hand. Run: npm run catalog:build
export type RawRoute = {
  id: string;
  channel: string;
  kind: "points" | "flat_pct" | "unknown" | "excluded";
  verified: boolean;
  unit?: number;
  base_pts?: number;
  mult?: number;
  discount_pct?: number;
  reward_pct?: number;
  bonus_cap_pts?: number;
  note?: string;
};
export type RawCard = { id: string; name: string; issuer: string; aliases: string[]; routes: RawRoute[] };

/** Largest voucher the research assumes a bank portal sells. */
export const MAX_VOUCHER_DENOMINATION = ${data.maxVoucherDenomination};

export const CATALOG_DATA: RawCard[] = ${JSON.stringify(data.cards, null, 2)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const data = buildCatalogData(JSON.parse(fs.readFileSync(SOURCE, 'utf8')));
  fs.writeFileSync(OUT, render(data));
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${data.cards.length} cards`);
}
