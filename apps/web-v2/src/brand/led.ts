export const LED_ROWS = 7;
export const LED_COLS = 5;
export const LED_CHARS = Object.keys(G).filter((c) => c !== " ");

export type LedCell = { col: number; row: number };

/** Lit cells for one line of text, plus its width in columns. Unknown characters render as a space. */
export function ledLine(text: string): { cells: LedCell[]; cols: number } {
  const cells: LedCell[] = [];
  const chars = [...text.toUpperCase()];
  chars.forEach((ch, i) => {
    const rows = (G[ch] ?? G[" "]).split("/");
    rows.forEach((row, r) => {
      for (let c = 0; c < LED_COLS; c++) if (row[c] === "#") cells.push({ col: i * (LED_COLS + 1) + c, row: r });
    });
  });
  return { cells, cols: Math.max(0, chars.length * (LED_COLS + 1) - 1) };
}

/** Lay out one or more lines, centred. Rows are 7 dots tall with a 2-dot gap between lines. */
export function ledLayout(lines: string[]): { cells: LedCell[]; cols: number; rows: number } {
  const laid = lines.map(ledLine);
  const cols = Math.max(1, ...laid.map((l) => l.cols));
  const cells: LedCell[] = [];
  laid.forEach((l, i) => {
    const off = Math.floor((cols - l.cols) / 2);
    for (const c of l.cells) cells.push({ col: c.col + off, row: c.row + i * (LED_ROWS + 2) });
  });
  return { cells, cols, rows: laid.length * LED_ROWS + (laid.length - 1) * 2 };
}
